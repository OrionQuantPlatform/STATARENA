// Execute the real unmodified consumer helpers on the actual HTTP bodies.
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { normalizeOpenCup, normalizeSupplementalCup } from "../../../dashboard/frontend/src/services/cup-matches.js";
import { buildKnockoutBracket, combineCupLegs, nativeKnockoutMatches } from "../../../dashboard/frontend/src/services/knockout-bracket.js";
import { matchdayGroups } from "../../../dashboard/frontend/src/services/competition-matchdays.js";
import { nationsStandings } from "../../../dashboard/frontend/src/services/nations-standings.js";
import { supplementalCupCatalog, mergeCupCatalog } from "../../../dashboard/frontend/src/services/cup-catalog.js";
const body=JSON.parse(readFileSync(process.argv[2],"utf8"));
const open=normalizeOpenCup(body.open.matches);
assert.equal(open.length,3);assert.deepEqual(open[1].penalties,[3,4]);
const ties=combineCupLegs(open);
const semi=ties.find((m)=>m.roundName==="Semi-finals");
assert.deepEqual(semi.score,[1,1]);assert.deepEqual(semi.penalties,[4,3]);
assert.deepEqual(buildKnockoutBracket(ties).rounds.map((r)=>r.key),["semi","final"]);
const natives=nativeKnockoutMatches(body.native.matches,body.native.rounds);
assert.deepEqual(natives.find((m)=>m.roundName==="Semi-finals").score,[1,1]);
const days=matchdayGroups(body.native.matches,body.days.matches);
assert.equal(days.flatMap((g)=>g.matches).length,3);
assert.equal(matchdayGroups(body.unknown.matches,body.unknownDays.matches)[0].key,"unknown");
const groups=nationsStandings(body.nations.matches);
assert.equal(groups.length,1);assert.equal(groups[0].group,1);
assert.equal(groups[0].rows[0].name,"Observed team 3");
const normalized=normalizeSupplementalCup(body.results,body.fixtures);
assert.deepEqual(normalized.map((m)=>m.status),["finished","finished","scheduled"]);
assert(supplementalCupCatalog(body.index).some((c)=>c.folder==="ESP_CUP_fixture"));
assert(mergeCupCatalog([],body.index,body.index.native).some((c)=>c.id==="l_000001"&&c.cupWorker));
console.log(JSON.stringify({openMatches:open.length,semiScore:semi.score,semiPenalties:semi.penalties,nativeTies:natives.length,matchdayGroups:days.length,nationsGroups:groups.length,tableMatches:normalized.length}));
