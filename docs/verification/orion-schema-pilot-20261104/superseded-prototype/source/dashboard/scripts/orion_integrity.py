"""Compile the approved history and transaction guards; no database connection."""
from orion_schema import MODEL, ROOT, TABLES, cols, ident, literal, relation, short_name

VERSIONED = {n: t for n, t in TABLES.items() if "row_version_id" in t["columns"] and not t.get("history_of") and n not in {"ingest.dataset_snapshot_rows", "ingest.field_states", "ingest.record_row_links"}}
PROTECTED = {"ingest.sources", "ingest.source_datasets", "ingest.media_assets", "football.players", "football.teams", "football.competitions", "football.competition_seasons", "football.countries", "football.associations", "football.coaches", "football.venues", "football.metric_definitions", "football.periods", "football.positions"}
BASE = r"""
-- SQL JSON values below are transient representations of one typed row for hashes;
-- no response body/document is persisted. Historical storage is typed SQL only.
CREATE FUNCTION ingest.row_key(p_row jsonb,p_columns text[]) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path=pg_catalog AS $$
 SELECT jsonb_agg(p_row->column_name ORDER BY ordinal)::text
 FROM unnest(p_columns) WITH ORDINALITY q(column_name,ordinal)
$$;
CREATE FUNCTION ingest.row_fingerprint(p_row jsonb) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path=pg_catalog AS $$
 SELECT encode(sha256(convert_to((p_row-ARRAY['row_version_id','updated_at'])::text,'UTF8')),'hex')
$$;
CREATE FUNCTION ingest.immutable_row() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Immutable SQL version or sealed content cannot be changed'; END
$$;
CREATE FUNCTION ingest.finish_version(p_id bigint,p_relation text,p_key text,p_row jsonb,p_tombstone boolean) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest SET timezone='UTC' AS $$
DECLARE source_record bigint; transform text; kind text;
BEGIN
 transform:=nullif(current_setting('statarena.transform_version',true),'');
 IF transform IS NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='A declared transform version is required'; END IF;
 source_record:=coalesce((p_row->>'source_record_id')::bigint,nullif(current_setting('statarena.source_record_id',true),'')::bigint);
 kind:=CASE WHEN source_record IS NOT NULL THEN 'provider' ELSE coalesce(nullif(current_setting('statarena.provenance_kind',true),''),'manual') END;
 INSERT INTO ingest.row_versions(id,relation_code,logical_key,revision_no,source_record_id,provenance_kind,transform_version,content_sha256,is_tombstone)
 OVERRIDING SYSTEM VALUE
 SELECT p_id,p_relation,p_key,coalesce(max(revision_no),0)+1,source_record,kind,transform,ingest.row_fingerprint(p_row),p_tombstone
 FROM ingest.row_versions WHERE relation_code=p_relation AND logical_key=p_key;
END
$$;
CREATE FUNCTION ingest.capture_canonical() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest,football,analytics SET timezone='UTC' AS $$
DECLARE row_data jsonb; row_key text; relation_name text:=TG_TABLE_SCHEMA||'.'||TG_TABLE_NAME; keys text[]:=TG_ARGV[0]::text[]; history_name text:=TG_ARGV[1]; version_id bigint;
BEGIN
 row_data:=CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
 row_key:=ingest.row_key(row_data,keys);
 IF TG_WHEN='BEFORE' THEN
  PERFORM pg_advisory_xact_lock(hashtextextended('orion-row:'||relation_name||':'||row_key,0));
  IF TG_OP='DELETE' THEN
   IF history_name='' OR TG_ARGV[2]='protected' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Stable identities and append-only observations cannot be deleted'; END IF;
   version_id:=nextval(pg_get_serial_sequence('ingest.row_versions','id'));
   OLD.row_version_id:=version_id;
   PERFORM ingest.finish_version(version_id,relation_name,row_key,to_jsonb(OLD),true);
   EXECUTE format('INSERT INTO %I.%I SELECT ($1).*',split_part(history_name,'.',1),split_part(history_name,'.',2)) USING OLD;
   RETURN OLD;
  END IF;
  IF TG_OP='UPDATE' THEN
   IF ingest.row_key(to_jsonb(OLD),keys)<>row_key THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='A logical identity cannot be moved by UPDATE'; END IF;
   IF NEW.row_version_id<>OLD.row_version_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Row version is generated by the database'; END IF;
   IF ingest.row_fingerprint(row_data)=ingest.row_fingerprint(to_jsonb(OLD)) AND coalesce(current_setting('statarena.force_version',true),'')<>'true' THEN RETURN OLD; END IF;
   IF history_name='' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Append-only observation requires a new identity for a correction'; END IF;
  ELSIF NEW.row_version_id IS NOT NULL THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Do not supply a generated row version';
  END IF;
  NEW.row_version_id:=nextval(pg_get_serial_sequence('ingest.row_versions','id'));
  IF row_data ? 'updated_at' THEN NEW.updated_at:=statement_timestamp(); END IF;
  RETURN NEW;
 END IF;
 IF TG_OP='UPDATE' AND NEW.row_version_id=OLD.row_version_id THEN RETURN NEW; END IF;
 PERFORM ingest.finish_version(NEW.row_version_id,relation_name,row_key,to_jsonb(NEW),false);
 IF history_name<>'' THEN
  EXECUTE format('INSERT INTO %I.%I SELECT ($1).*',split_part(history_name,'.',1),split_part(history_name,'.',2)) USING NEW;
 END IF;
 RETURN NEW;
END
$$;
CREATE FUNCTION ingest.check_typed_representation() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest SET timezone='UTC' AS $$
DECLARE target text; key_columns text[]; payload jsonb; actual_key text;
BEGIN
 SELECT history_relation INTO STRICT target FROM ingest.relation_contracts WHERE relation_code=NEW.relation_code;
 EXECUTE format('SELECT to_jsonb(t) FROM %I.%I t WHERE row_version_id=$1',split_part(target,'.',1),split_part(target,'.',2)) INTO payload USING NEW.id;
 IF payload IS NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Retained version has no typed representation'; END IF;
 SELECT array_agg(a.attname ORDER BY k.ordinality) INTO key_columns FROM pg_index i
 CROSS JOIN LATERAL unnest(i.indkey) WITH ORDINALITY k(attnum,ordinality)
 JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=k.attnum
 WHERE i.indrelid=NEW.relation_code::regclass AND i.indisprimary;
 actual_key:=ingest.row_key(payload,key_columns);
 IF actual_key<>NEW.logical_key OR ingest.row_fingerprint(payload)<>NEW.content_sha256 THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Typed representation does not match its relation, logical key or hash';
 END IF;
 RETURN NULL;
END
$$;
CREATE FUNCTION ingest.check_history_insert() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest SET timezone='UTC' AS $$
DECLARE version ingest.row_versions%ROWTYPE;
BEGIN
 SELECT * INTO STRICT version FROM ingest.row_versions WHERE id=NEW.row_version_id;
 IF version.relation_code<>TG_ARGV[0] OR version.logical_key<>ingest.row_key(to_jsonb(NEW),TG_ARGV[1]::text[]) OR version.content_sha256<>ingest.row_fingerprint(to_jsonb(NEW)) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Historical values must match their registered typed version';
 END IF;
 RETURN NEW;
END
$$;
CREATE FUNCTION ingest.match_write_lock() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
DECLARE match_id bigint;
BEGIN
 FOR match_id IN SELECT DISTINCT v FROM unnest(ARRAY[
  CASE WHEN TG_OP<>'INSERT' THEN (to_jsonb(OLD)->>TG_ARGV[0])::bigint END,
  CASE WHEN TG_OP<>'DELETE' THEN (to_jsonb(NEW)->>TG_ARGV[0])::bigint END]) q(v) WHERE v IS NOT NULL ORDER BY v LOOP
  PERFORM pg_advisory_xact_lock(hashtextextended('orion-match:'||match_id::text,0));
 END LOOP;
 IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END
$$;
CREATE FUNCTION ingest.check_match_graph() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest,football AS $$
DECLARE match_key bigint; m football.matches%ROWTYPE; sides integer; known integer; distinct_teams integer; invalid_labels integer; facts boolean;
BEGIN
 FOR match_key IN SELECT DISTINCT v FROM unnest(ARRAY[
  CASE WHEN TG_OP<>'INSERT' THEN (to_jsonb(OLD)->>TG_ARGV[0])::bigint END,
  CASE WHEN TG_OP<>'DELETE' THEN (to_jsonb(NEW)->>TG_ARGV[0])::bigint END]) q(v) WHERE v IS NOT NULL LOOP
  SELECT * INTO m FROM football.matches WHERE id=match_key;
  IF NOT FOUND THEN CONTINUE; END IF;
  SELECT count(*),count(team_id),count(DISTINCT team_id),count(*) FILTER(WHERE team_id IS NULL AND nullif(btrim(participant_label),'') IS NULL)
  INTO sides,known,distinct_teams,invalid_labels FROM football.match_teams WHERE match_id=match_key;
  facts:=EXISTS(SELECT 1 FROM football.player_match_stats WHERE match_id=match_key) OR EXISTS(SELECT 1 FROM football.team_match_stats WHERE match_id=match_key) OR EXISTS(SELECT 1 FROM football.shots WHERE match_id=match_key);
  IF m.publication_state='published' AND (sides<>2 OR invalid_labels>0 OR known<>distinct_teams OR (known<>2 AND m.status NOT IN ('not_started','postponed','canceled','unknown'))) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Published match needs two distinct valid participants';
  END IF;
  IF facts AND (sides<>2 OR known<>2 OR distinct_teams<>2) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Sport facts require two identified match participants';
  END IF;
  IF EXISTS(SELECT 1 FROM football.shots s WHERE s.match_id=match_key AND s.player_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM football.match_players p WHERE (p.match_id,p.player_id,p.team_id)=(s.match_id,s.player_id,s.team_id))) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Resolved shot actor must belong to the same match and team';
  END IF;
 END LOOP;
 RETURN NULL;
END
$$;
CREATE FUNCTION ingest.check_field_contract() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest AS $$
BEGIN
 IF NEW.field_code !~ '^[a-z][a-z0-9_]*$' OR NOT EXISTS(SELECT 1 FROM ingest.relation_contracts c JOIN pg_attribute a ON a.attrelid=c.relation_code::regclass AND a.attname=NEW.target_column AND a.attnum>0 AND NOT a.attisdropped WHERE c.relation_code=NEW.relation_code) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Field must bind a registered semantic code to a typed column';
 END IF;
 RETURN NEW;
END
$$;
CREATE FUNCTION ingest.check_field_state() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM ingest.dataset_snapshot_rows r JOIN ingest.dataset_snapshots s ON s.id=r.snapshot_id WHERE r.row_version_id=NEW.row_version_id AND s.status='sealed') THEN
  RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Native field state cannot be added to sealed content';
 END IF;
 IF (NEW.source_state IN ('absent','null','empty_array','empty_object') AND num_nonnulls(NEW.source_text,NEW.source_number,NEW.source_boolean)<>0)
 OR (NEW.source_state='number' AND (NEW.source_number IS NULL OR num_nonnulls(NEW.source_text,NEW.source_boolean)<>0))
 OR (NEW.source_state='string' AND (NEW.source_text IS NULL OR num_nonnulls(NEW.source_number,NEW.source_boolean)<>0))
 OR (NEW.source_state='boolean' AND (NEW.source_boolean IS NULL OR num_nonnulls(NEW.source_text,NEW.source_number)<>0)) THEN
  RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Native field state and scalar value disagree';
 END IF;
 RETURN NEW;
END
$$;
CREATE FUNCTION ingest.snapshot_member_guard() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest AS $$
DECLARE snapshot_key bigint; state text;
BEGIN
 FOR snapshot_key IN SELECT DISTINCT v FROM unnest(ARRAY[CASE WHEN TG_OP<>'INSERT' THEN OLD.snapshot_id END,CASE WHEN TG_OP<>'DELETE' THEN NEW.snapshot_id END]) q(v) WHERE v IS NOT NULL ORDER BY v LOOP
  SELECT status INTO state FROM ingest.dataset_snapshots WHERE id=snapshot_key FOR UPDATE;
  IF state='sealed' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Sealed snapshot membership is immutable'; END IF;
 END LOOP;
 IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END
$$;
CREATE FUNCTION ingest.snapshot_fingerprint(p_snapshot bigint) RETURNS text
LANGUAGE sql STABLE SET search_path=pg_catalog,ingest SET timezone='UTC' AS $$
 SELECT encode(sha256(convert_to(coalesce(string_agg(
  jsonb_build_array(r.relation_code,r.logical_key,r.row_version_id,v.content_sha256,v.is_tombstone,
   (SELECT jsonb_agg(jsonb_build_array(f.field_code,f.source_state,f.source_text,f.source_number,f.source_boolean) ORDER BY f.field_code) FROM ingest.field_states f WHERE f.row_version_id=v.id))::text,
  E'\n' ORDER BY r.relation_code,r.logical_key),''),'UTF8')),'hex')
 FROM ingest.dataset_snapshot_rows r JOIN ingest.row_versions v ON v.id=r.row_version_id WHERE r.snapshot_id=p_snapshot
$$;
CREATE FUNCTION ingest.snapshot_guard() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest,football SET timezone='UTC' AS $$
DECLARE digest text;
BEGIN
 IF TG_OP='DELETE' THEN
  IF OLD.status='sealed' THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Sealed snapshot cannot be deleted'; END IF;
  RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' AND OLD.status='sealed' AND NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION USING ERRCODE='55000',MESSAGE='Sealed snapshot cannot be changed'; END IF;
 IF NEW.status='sealed' THEN
  PERFORM ingest.validate_snapshot(NEW.id);
  digest:=ingest.snapshot_fingerprint(NEW.id);
  IF NEW.manifest_sha256 IS NOT NULL AND NEW.manifest_sha256<>digest THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Snapshot manifest does not match its SQL content'; END IF;
  NEW.manifest_sha256:=digest;
  NEW.sealed_at:=coalesce(NEW.sealed_at,statement_timestamp());
 END IF;
 RETURN NEW;
END
$$;
"""

def compile_sql():
    out = [BASE]
    for name, table in VERSIONED.items():
        history = name+"_history" if name+"_history" in TABLES else name
        out.append(f"INSERT INTO ingest.relation_contracts(relation_code,history_relation,contract_version,grain_definition) VALUES ({literal(name)},{literal(history)},'orion-v1',{literal(table['grain'])});")
        for column, spec in table["columns"].items():
            out.append(f"INSERT INTO ingest.field_contracts(relation_code,field_code,target_column,definition) VALUES ({literal(name)},{literal(column)},{literal(column)},{literal(spec['description'])});")
        args = ",".join([literal("{"+",".join(table["primary_key"]["columns"])+"}"),literal("" if history==name else history),literal("protected" if name in PROTECTED else "fact")])
        # AFTER capture precedes PostgreSQL's immediate RI triggers alphabetically.
        # BEFORE reserves a sequence value only: ON CONFLICT DO NOTHING leaves no orphan registry row.
        out += [f"CREATE TRIGGER B_orion_capture_before BEFORE INSERT OR UPDATE OR DELETE ON {relation(name)} FOR EACH ROW EXECUTE FUNCTION ingest.capture_canonical({args});",
                f'CREATE TRIGGER "A_orion_capture_after" AFTER INSERT OR UPDATE ON {relation(name)} FOR EACH ROW EXECUTE FUNCTION ingest.capture_canonical({args});']
        if history != name:
            out += [f"CREATE TRIGGER orion_history_insert BEFORE INSERT ON {relation(history)} FOR EACH ROW EXECUTE FUNCTION ingest.check_history_insert({literal(name)},{literal('{'+','.join(table['primary_key']['columns'])+'}')});"]
    out += ["CREATE CONSTRAINT TRIGGER orion_typed_version AFTER INSERT ON ingest.row_versions DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ingest.check_typed_representation();",
            "CREATE TRIGGER orion_field_contract BEFORE INSERT OR UPDATE ON ingest.field_contracts FOR EACH ROW EXECUTE FUNCTION ingest.check_field_contract();",
            "CREATE TRIGGER orion_field_state BEFORE INSERT ON ingest.field_states FOR EACH ROW EXECUTE FUNCTION ingest.check_field_state();",
            "CREATE TRIGGER orion_snapshot_members BEFORE INSERT OR UPDATE OR DELETE ON ingest.dataset_snapshot_rows FOR EACH ROW EXECUTE FUNCTION ingest.snapshot_member_guard();",
            "CREATE TRIGGER orion_snapshot_documents BEFORE INSERT OR UPDATE OR DELETE ON ingest.dataset_snapshot_documents FOR EACH ROW EXECUTE FUNCTION ingest.snapshot_member_guard();",
            "CREATE TRIGGER orion_snapshot BEFORE INSERT OR UPDATE OR DELETE ON ingest.dataset_snapshots FOR EACH ROW EXECUTE FUNCTION ingest.snapshot_guard();",
            "CREATE INDEX orion_snapshot_row_version_idx ON ingest.dataset_snapshot_rows(row_version_id,snapshot_id);"]
    immutable = {n for n,t in TABLES.items() if t.get("history_of")} | {"ingest.row_versions","ingest.field_states","ingest.source_records","ingest.record_row_links","ingest.schema_migrations","ingest.relation_contracts"}
    for name in sorted(immutable):
        out += [f"CREATE TRIGGER orion_immutable BEFORE UPDATE OR DELETE ON {relation(name)} FOR EACH ROW EXECUTE FUNCTION ingest.immutable_row();",
                f"CREATE TRIGGER orion_no_truncate BEFORE TRUNCATE ON {relation(name)} FOR EACH STATEMENT EXECUTE FUNCTION ingest.immutable_row();"]
    for name, table in TABLES.items():
        if not name.startswith("football.") or table.get("history_of"):
            continue
        key = "id" if name=="football.matches" else "match_id" if "match_id" in table["columns"] else None
        if key:
            out += [f"CREATE TRIGGER A_orion_match_lock BEFORE INSERT OR UPDATE OR DELETE ON {relation(name)} FOR EACH ROW EXECUTE FUNCTION ingest.match_write_lock({literal(key)});",
                    f"CREATE CONSTRAINT TRIGGER orion_match_graph AFTER INSERT OR UPDATE OR DELETE ON {relation(name)} DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ingest.check_match_graph({literal(key)});"]
    validation = ["CREATE FUNCTION ingest.validate_snapshot(p_snapshot bigint) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,ingest,football,analytics AS $$ BEGIN"]
    for name, table in VERSIONED.items():
        source = name+"_history" if name+"_history" in TABLES else name
        for fk in table["foreign_keys"]:
            target = fk["references"]["table"]
            if target not in VERSIONED:
                continue
            target_history = target+"_history" if target+"_history" in TABLES else target
            nonnull = " AND ".join("a."+ident(c)+" IS NOT NULL" for c in fk["columns"])
            equality = " AND ".join("a."+ident(a)+"=b."+ident(b) for a,b in zip(fk["columns"],fk["references"]["columns"]))
            validation.append(f"IF EXISTS(SELECT 1 FROM ingest.dataset_snapshot_rows r JOIN ingest.row_versions av ON av.id=r.row_version_id JOIN {relation(source)} a ON a.row_version_id=r.row_version_id WHERE r.snapshot_id=p_snapshot AND r.relation_code={literal(name)} AND NOT av.is_tombstone AND {nonnull} AND NOT EXISTS(SELECT 1 FROM ingest.dataset_snapshot_rows s JOIN ingest.row_versions bv ON bv.id=s.row_version_id JOIN {relation(target_history)} b ON b.row_version_id=s.row_version_id WHERE s.snapshot_id=p_snapshot AND s.relation_code={literal(target)} AND NOT bv.is_tombstone AND {equality})) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE={literal('Snapshot FK mismatch: '+fk['name'])}; END IF;")
    validation.append("END $$;")
    out += validation
    out += ["REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA ingest FROM PUBLIC;",
            "DO $$ BEGIN IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='statarena_ingest') THEN GRANT USAGE ON SCHEMA ingest,football,analytics TO statarena_ingest; GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA ingest,football,analytics TO statarena_ingest; GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA ingest,football,analytics TO statarena_ingest; END IF; IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='statarena_runtime') THEN GRANT USAGE ON SCHEMA football,analytics,ingest TO statarena_runtime; GRANT SELECT ON ALL TABLES IN SCHEMA football,analytics TO statarena_runtime; GRANT SELECT ON ingest.dataset_snapshots,ingest.dataset_snapshot_rows,ingest.row_versions,ingest.public_aliases,ingest.media_assets TO statarena_runtime; END IF; END $$;"]
    for name in sorted(immutable | {"ingest.field_contracts"}):
        out.append(f"DO $$ BEGIN IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='statarena_ingest') THEN REVOKE INSERT,UPDATE,DELETE ON {relation(name)} FROM statarena_ingest; END IF; END $$;")
    out.append("SELECT set_config('statarena.transform_version','orion-bootstrap-v1',true);")
    for name, rows in MODEL["seed_data"].items():
        if name in TABLES:
            for row in rows:
                out.append(f"INSERT INTO {relation(name)} ({cols(row)}) VALUES ({', '.join(literal(v) for v in row.values())});")
    return "\n\n".join(out)+"\n"

if __name__ == "__main__":
    path = ROOT/"dashboard/backend/migrations/013_orion_integrity.sql"
    path.write_text(compile_sql())
    print({"file":str(path.relative_to(ROOT)),"versionedRelations":len(VERSIONED)})
