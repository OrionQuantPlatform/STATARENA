def quoted(name):
    return '"' + name.replace('"', '""') + '"'


def fields(model, prefix=()):
    for name, kind in model.items():
        key = (*prefix, name)
        yield key, kind
        if isinstance(kind, dict):
            yield from fields(kind, key)


def leaves(model):
    return [(p, k) for p, k in fields(model) if isinstance(k, str)]


def dbname(path):
    # The SQL position column orders siblings. Provider positions remain queryable separately.
    return "provider_position" if path == ("position",) else "_".join(path)


def column_lines(model):
    return [f"{quoted(dbname(path))} {kind}" for path, kind in leaves(model)]


def projected(model, alias, prefix=(), depth=0):
    """Build HTTP JSON only as a SQL result. Stored rows use ordinary SQL types."""
    pairs = []
    for name, kind in model.items():
        key = (*prefix, name)
        dotted = ".".join(key)
        if isinstance(kind, Children):
            child = f"r{depth + 1}"
            expr = projected(kind.fields, child, depth=depth + 1)
            aggregate = (
                f"jsonb_object_agg({child}.metric_label, {expr})"
                if kind.keyed
                else f"jsonb_agg({expr} ORDER BY {child}.position)"
            )
            empty = "{}" if kind.keyed else "[]"
            expr = (
                f"(SELECT coalesce({aggregate}, '{empty}'::jsonb) FROM statarena_app.{kind.table} {child}\n"
                f" WHERE {child}.resource_id={alias}.resource_id AND {child}.parent_no={alias}.record_no)"
            )
        elif isinstance(kind, dict):
            expr = projected(kind, alias, key, depth)
        else:
            expr = f"{alias}.{quoted(dbname(key))}"
        if not isinstance(kind, str):
            expr = f"CASE WHEN '{dotted}'=ANY({alias}.null_groups) THEN NULL ELSE {expr} END"
        pairs.append(f"'{name}', {expr}")
    missing = alias + ".missing"
    if prefix:
        candidates = ", ".join(
            f"CASE WHEN '{'.'.join((*prefix, name))}'=ANY({missing}) THEN '{name}' END"
            for name in model
        )
        missing = f"array_remove(ARRAY[{candidates}],NULL)"
    # PostgreSQL functions accept at most 100 arguments (50 key/value pairs).
    if len(pairs) > 50:
        chunks = [
            "jsonb_build_object(" + ",\n".join(pairs[i : i + 50]) + ")"
            for i in range(0, len(pairs), 50)
        ]
        return "((" + " || ".join(chunks) + ") - " + missing + ")"
    return "(jsonb_build_object(" + ",\n".join(pairs) + ") - " + missing + ")"


def data_function(family, spec):
    projection = projected(spec.fields, "r")
    if family == "players":
        projection += " -> 'players'"
    function = f"statarena_app.detail_data_{family}"
    return (
        f"CREATE OR REPLACE FUNCTION {function}(rid bigint) RETURNS jsonb LANGUAGE sql STABLE AS $$\n"
        f"SELECT {projection} FROM statarena_app.{spec.table} r WHERE r.resource_id=rid;\n$$;"
    )


def generate():
    sql = [
        "-- Generated by python3 dashboard/scripts/relational_match_ddl.py. Edit the domain mapping and regenerate.",
        "CREATE SCHEMA IF NOT EXISTS statarena_app;",
        "CREATE TABLE IF NOT EXISTS statarena_app.match_details (\n "
        + ",\n ".join(
            [
                "match_id text PRIMARY KEY",
                "has_context boolean NOT NULL DEFAULT false",
                "context_digest char(64)",
                "missing text[] NOT NULL DEFAULT '{}'",
                "null_groups text[] NOT NULL DEFAULT '{}'",
                *column_lines(context),
            ]
        )
        + "\n);",
        """CREATE TABLE IF NOT EXISTS statarena_app.match_families (
 resource_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 match_id text NOT NULL REFERENCES statarena_app.match_details ON DELETE CASCADE,
 family text NOT NULL,
 subject_id text NOT NULL,
 params text NOT NULL,
 status integer,
 has_data boolean NOT NULL,
 has_error boolean NOT NULL,
 error_object boolean NOT NULL,
 error_code text, error_message text,
 error_has_code boolean NOT NULL, error_has_message boolean NOT NULL,
 source_digest char(64) NOT NULL,
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(match_id,params,subject_id,family)
);""",
    ]

    def table(spec, parent=None):
        lines = [
            "resource_id bigint NOT NULL REFERENCES statarena_app.match_families ON DELETE CASCADE",
            "record_no integer NOT NULL",
            "missing text[] NOT NULL",
            "null_groups text[] NOT NULL",
        ]
        if parent:
            lines += ["parent_no integer NOT NULL", "position integer NOT NULL"]
        if spec.keyed:
            lines += ["metric_label text NOT NULL"]
        lines += [*column_lines(spec.fields), "PRIMARY KEY(resource_id,record_no)"]
        if parent:
            lines += [
                f"FOREIGN KEY(resource_id,parent_no) REFERENCES statarena_app.{parent}(resource_id,record_no) ON DELETE CASCADE",
                "UNIQUE(resource_id,parent_no,position)",
            ]
        else:
            lines += ["CHECK (record_no=0)"]
        sql.append(
            f"CREATE TABLE IF NOT EXISTS statarena_app.{spec.table} (\n "
            + ",\n ".join(lines)
            + "\n);"
        )
        for _, child in fields(spec.fields):
            if isinstance(child, Children):
                table(child, spec.table)

    sql.append("""CREATE OR REPLACE VIEW statarena_app.match_detail_versions AS
SELECT c.match_id,
       encode(sha256(convert_to(coalesce(c.context_digest,'') || '|' ||
         string_agg(f.family || ':' || f.source_digest, '|' ORDER BY f.family), 'UTF8')), 'hex') AS version
FROM statarena_app.match_details c
JOIN statarena_app.match_families f ON f.match_id=c.match_id AND f.params='{}' AND f.subject_id=''
GROUP BY c.match_id, c.context_digest;""")
    alternatives = []
    for family, spec in families_v004.items():
        table(spec)
        function = f"statarena_app.detail_data_{family}"
        sql.append(data_function(family, spec))
        alternatives.append(f"WHEN '{family}' THEN {function}(f.resource_id)")
    alternatives += [
        "WHEN 'single_shot' THEN statarena_app.detail_data_shots(f.resource_id) #> '{periods,0,shots,0}'",
        "WHEN 'single_player' THEN statarena_app.detail_data_players(f.resource_id) -> 0",
        "WHEN 'single_halves' THEN (SELECT (payload #> '{players,0}') || (payload-'players') FROM statarena_app.detail_data_player_halves(f.resource_id) payload)",
        "WHEN 'single_advanced' THEN statarena_app.detail_data_advanced_players(f.resource_id) #> '{players,0}'",
    ]
    sql.append(
        "CREATE OR REPLACE FUNCTION statarena_app.detail_response(f statarena_app.match_families)\n"
        "RETURNS jsonb LANGUAGE sql STABLE AS $$\n SELECT jsonb_build_object('status', f.status)\n"
        " || CASE WHEN f.has_data THEN jsonb_build_object('data', CASE f.family\n"
        + "\n".join(alternatives)
        + "\nEND) ELSE '{}'::jsonb END\n"
        " || CASE WHEN f.has_error THEN jsonb_build_object('error', CASE WHEN f.error_object THEN\n"
        " (CASE WHEN f.error_has_code THEN jsonb_build_object('code',f.error_code) ELSE '{}'::jsonb END) ||\n"
        " (CASE WHEN f.error_has_message THEN jsonb_build_object('message',f.error_message) ELSE '{}'::jsonb END)\n"
        " ELSE NULL END) ELSE '{}'::jsonb END;\n$$;"
    )
    sql.append(
        "CREATE OR REPLACE FUNCTION statarena_app.detail_context(c statarena_app.match_details)\n"
        "RETURNS jsonb LANGUAGE sql STABLE AS $$\n SELECT CASE WHEN c.has_context THEN "
        + projected(context, "c")
        + " ELSE '{}'::jsonb END;\n$$;"
    )
    return "\n\n".join(sql) + "\n"


def optional_column(table, key, kind):
    return f"""DO $upgrade$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='statarena_app.{table}'::regclass
                   AND attname='{key}' AND NOT attisdropped) THEN
        ALTER TABLE statarena_app.{table} ADD COLUMN {key} {kind};
        UPDATE statarena_app.{table} SET missing=array_append(missing,'{key}')
        WHERE NOT ('{key}'=ANY(missing));
    END IF;
END
$upgrade$;"""


